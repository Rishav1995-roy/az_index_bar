/// About 130 invented contacts, deterministic.
List<String> sampleContacts() {
  final List<String> out = <String>[..._extra];
  for (int i = 0; i < _first.length; i++) {
    out.add('${_first[i]} ${_last[i]}');
    out.add('${_first[i]} ${_last[(i * 7 + 3) % _last.length]}');
    if (i % 3 == 0) {
      out.add('${_first[i]} ${_last[(i * 5 + 11) % _last.length]}');
    }
  }
  // Leave Q, X and Y rare so some letters are disabled.
  out.removeWhere((String s) => s.startsWith('X'));
  return out;
}

